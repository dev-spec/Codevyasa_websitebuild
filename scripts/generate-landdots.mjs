// One-time generator: rasterizes public-domain Natural Earth land polygons into
// an even-density set of [lat,lng] dots → components/three/landDots.ts
// Source data: nvkelso/natural-earth-vector (public domain). Not needed at runtime.
import { readFileSync, writeFileSync } from 'node:fs';

const SRC = process.argv[2] || 'C:/Users/Admin/AppData/Local/Temp/claude/geo/ne_110m_land.geojson';
const OUT = new URL('../components/three/landDots.ts', import.meta.url);
const STEP = Number(process.argv[3]) || 1.0; // degrees between latitude bands (lng scales by cos(lat))

const geo = JSON.parse(readFileSync(SRC, 'utf8'));

/** Flatten every feature into a list of polygons; each polygon = array of rings. */
const polygons = [];
for (const f of geo.features) {
  const g = f.geometry;
  if (!g) continue;
  const polys = g.type === 'Polygon' ? [g.coordinates] : g.type === 'MultiPolygon' ? g.coordinates : [];
  for (const rings of polys) {
    let minLng = 180, minLat = 90, maxLng = -180, maxLat = -90;
    for (const ring of rings) {
      for (const [lng, lat] of ring) {
        if (lng < minLng) minLng = lng;
        if (lng > maxLng) maxLng = lng;
        if (lat < minLat) minLat = lat;
        if (lat > maxLat) maxLat = lat;
      }
    }
    polygons.push({ rings, bbox: [minLng, minLat, maxLng, maxLat] });
  }
}

// Even-odd ray cast across all rings of a polygon (holes handled automatically).
function inPolygon(poly, x, y) {
  const [minLng, minLat, maxLng, maxLat] = poly.bbox;
  if (x < minLng || x > maxLng || y < minLat || y > maxLat) return false;
  let inside = false;
  for (const ring of poly.rings) {
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
      const xi = ring[i][0], yi = ring[i][1], xj = ring[j][0], yj = ring[j][1];
      if (((yi > y) !== (yj > y)) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
    }
  }
  return inside;
}

const isLand = (lng, lat) => polygons.some((p) => inPolygon(p, lng, lat));

const dots = [];
for (let lat = -84; lat <= 84; lat += STEP) {
  const lngStep = STEP / Math.max(Math.cos((lat * Math.PI) / 180), 0.12);
  for (let lng = -180; lng < 180; lng += lngStep) {
    if (isLand(lng, lat)) {
      dots.push(Math.round(lat * 10), Math.round(lng * 10));
    }
  }
}

const count = dots.length / 2;
const packed = Buffer.from(Int16Array.from(dots).buffer).toString('base64');
const body = `// AUTO-GENERATED by scripts/generate-landdots.mjs — public-domain Natural Earth land.
// Land coordinates packed as a base64 Int16Array of [lat*10, lng*10, ...], decoded at
// runtime in GlobeScene. Packed (not a giant JS array literal) so the module compiles fast.
export const landDotsPacked = ${JSON.stringify(packed)};
export const landDotCount = ${count};
`;
writeFileSync(OUT, body);
console.log(`[landdots] ${count} land dots → components/three/landDots.ts (${(body.length / 1024).toFixed(0)} KB packed)`);
